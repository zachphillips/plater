import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
export async function journey({ page, step, expect, note }) {
  const b = JSON.parse(fs.readFileSync(process.env.UPLOAD_BENCH_FILE, 'utf8'));
  const weak = Boolean(process.env.UPLOAD_EXPECT_WEAK);
  const images = path.join(b.siteDir, 'images');
  const outside = fs.mkdtempSync(path.join(path.dirname(b.siteDir), 'plater-upload-outside-'));
  const bytes = Buffer.from('Synthetic whole image bytes for preservation proof');
  const name = createHash('sha256').update(bytes).digest('hex').slice(0, 8) + '-proof.png';
  const results = [];
  const reset = () => { fs.rmSync(images, { recursive: true, force: true }); fs.mkdirSync(images); };
  const upload = async () => { const r = await fetch(b.url + 'api/upload', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ filename: 'proof.png', dataBase64: bytes.toString('base64') }) }); return { status: r.status, out: await r.json() }; };
  reset();
  const dest = path.join(images, name), original = 'A different pre-existing asset must survive';
  fs.writeFileSync(dest, original);
  const collision = await upload();
  expect(collision.status === (weak ? 200 : 409) && (fs.readFileSync(dest, 'utf8') === original) === !weak, 'a hash-prefix filename collision never replaces a different existing asset');
  results.push({ case: 'existing different asset', ...collision, originalKept: fs.readFileSync(dest, 'utf8') === original });
  reset();
  const privateFile = path.join(outside, 'synthetic-private.txt'); fs.writeFileSync(privateFile, original);
  fs.symlinkSync(privateFile, dest);
  const symlink = await upload();
  expect(symlink.status === (weak ? 200 : 409) && (fs.readFileSync(privateFile, 'utf8') === original) === !weak, 'upload never follows an existing file symlink into another file');
  results.push({ case: 'existing file symlink', ...symlink, outsideFileKept: fs.readFileSync(privateFile, 'utf8') === original });
  fs.rmSync(images, { recursive: true, force: true }); fs.symlinkSync(outside, images);
  const directory = await upload();
  expect(directory.status === (weak ? 200 : 403) && fs.existsSync(path.join(outside, name)) === weak, 'the image directory cannot redirect uploads outside the web root');
  results.push({ case: 'outside image directory', ...directory, wroteOutside: fs.existsSync(path.join(outside, name)) });
  reset();
  const first = await upload(), second = await upload();
  expect(first.status === 200 && second.status === 200 && fs.readFileSync(dest).equals(bytes), 'normal upload and identical retry preserve exactly the complete bytes');
  const served = await fetch(b.url + 'images/' + name);
  expect(served.status === 200 && Buffer.from(await served.arrayBuffer()).equals(bytes), 'the accepted image URL serves those exact bytes');
  expect(fs.readdirSync(images).every((n) => !n.endsWith('.plater-tmp')), 'successful uploads leave no temporary files');
  results.push({ case: 'whole accepted upload and identical retry', statuses: [first.status, second.status], wholeFile: true, served: served.status });
  note('Actual upload responses and file read-backs', results);
  await page.goto(b.url);
  await page.evaluate((data) => { const pre = document.createElement('pre'); pre.style.whiteSpace = 'pre-wrap'; pre.textContent = JSON.stringify(data, null, 2); document.querySelector('main').prepend(pre); }, results);
  await step(weak ? 'upload replaces existing assets and follows outside symlinks' : 'upload preserves existing assets and refuses outside symlinks');
}
